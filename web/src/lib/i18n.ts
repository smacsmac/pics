const DICTS: Record<Lang, Dict> = { en, fr, ko };

export function dict(lang: Lang): Dict {
  return DICTS[lang] ?? en;
}

export function monthNames(lang: Lang, style: 'short' | 'long' = 'short'): string[] {
  const fmt = new Intl.DateTimeFormat(LOCALE[lang], { month: style });
  return Array.from({ length: 12 }, (_, i) => fmt.format(new Date(2024, i, 1)));
}

export function formatDayHeading(ts: number, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE[lang], {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date(ts));
}

/** Étiquette courte pour la vue condensée, où la place est comptée. */
export function formatShortDay(ts: number, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE[lang], {
    day: 'numeric',
    month: 'short',
    year: '2-digit',
  }).format(new Date(ts));
}

export function formatMonthLabel(ts: number, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE[lang], { month: 'short', year: 'numeric' }).format(
    new Date(ts),
  );
}

export function formatDateTime(ts: number, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE[lang], {
    dateStyle: 'full',
    timeStyle: 'short',
  }).format(new Date(ts));
}

/**
 * Les bornes d'un moment. Une sortie d'après-midi donne « 12 juillet 2026,
 * 9 h – 17 h » ; un week-end, « 12 – 14 juillet 2026 ». Intl s'en charge selon
 * la langue, y compris pour le coréen.
 */
export function formatSpan(from: number, to: number, lang: Lang): string {
  const start = new Date(from);
  const end = new Date(to);
  const sameDay =
    start.getFullYear() === end.getFullYear() &&
    start.getMonth() === end.getMonth() &&
    start.getDate() === end.getDate();

  if (sameDay) {
    const day = new Intl.DateTimeFormat(LOCALE[lang], {
      day: 'numeric', month: 'long', year: 'numeric',
    }).format(start);
    const hours = new Intl.DateTimeFormat(LOCALE[lang], { timeStyle: 'short' });
    return `${day}, ${hours.formatRange(start, end)}`;
  }

  return new Intl.DateTimeFormat(LOCALE[lang], {
    day: 'numeric', month: 'long', year: 'numeric',
  }).formatRange(start, end);
}
